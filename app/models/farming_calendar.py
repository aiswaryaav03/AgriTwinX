from datetime import datetime
from app.database.db_setup import db

class FarmingCalendar(db.Model):
    """
    Stores the personalized, week-by-week farming schedule generated by Groq LLaMA 3.
    """
    __tablename__ = 'farming_calendars'

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    
    week_number = db.Column(db.Integer, nullable=False) # e.g., Week 1, 2, 3
    schedule_json = db.Column(db.JSON, nullable=False) # Structured daily action items
    
    groq_generated_at = db.Column(db.DateTime, default=db.func.current_timestamp())

    def __repr__(self):
        return f"<FarmingCalendar User:{self.user_id} Week:{self.week_number}>"